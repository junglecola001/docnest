/// Stable, typed identifiers shared by both ends.
library;

/// Identifier of a whitelisted root folder.
extension type const RootId(int value) {
  /// Parses [value], throwing [FormatException] when it is not an integer.
  static RootId parse(Object? value) {
    if (value is int) return RootId(value);
    if (value is String) {
      final parsed = int.tryParse(value);
      if (parsed != null) return RootId(parsed);
    }
    throw FormatException('Invalid RootId: $value');
  }
}

